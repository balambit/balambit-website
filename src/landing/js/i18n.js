class I18n {
    constructor() {
        this.language = localStorage.getItem('language') || this.getBrowserLanguage();
        this.init();
    }

    getBrowserLanguage() {
        const lang = navigator.language || navigator.userLanguage;
        return lang.startsWith('en') ? 'en' : 'es';
    }

    init() {
        // Since script is likely at the bottom, we can run immediately or on DOMContentLoaded
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', () => this.start());
        } else {
            this.start();
        }
    }

    start() {
        this.applyTranslations();
        this.setupSwitchers();
    }

    setLanguage(lang) {
        if (this.language === lang) return;
        this.language = lang;
        localStorage.setItem('language', lang);
        this.applyTranslations();
        this.updateActiveUI();

        // Update html lang attribute
        document.documentElement.lang = lang;
    }

    applyTranslations() {
        const dict = translations[this.language];

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = dict[key];

            if (translation) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = translation;
                } else {
                    el.innerHTML = translation;
                }
            }
        });

        // Update document title if needed
        if (dict.title) {
            document.title = dict.title;
        }
    }

    getTranslation(key) {
        return translations[this.language][key] || key;
    }

    setupSwitchers() {
        const switchers = document.querySelectorAll('[data-switch-lang]');
        switchers.forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.preventDefault();
                const lang = btn.getAttribute('data-switch-lang');
                this.setLanguage(lang);
            });
        });
        this.updateActiveUI();
    }

    updateActiveUI() {
        document.querySelectorAll('[data-switch-lang]').forEach(btn => {
            const lang = btn.getAttribute('data-switch-lang');
            if (lang === this.language) {
                btn.classList.add('font-bold');
                btn.classList.remove('opacity-50', 'grayscale');
            } else {
                btn.classList.remove('font-bold');
                btn.classList.add('opacity-50', 'grayscale');
            }
        });
    }
}

// Initialize globally
window.i18n = new I18n();
